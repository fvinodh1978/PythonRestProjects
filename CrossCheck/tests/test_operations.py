class TestSummation:
    def test_addition(self):
        """
        Test if addition of 1 and 1 results in 2.
        """
        assert 1 + 1 == 2

    def test_subtraction(self):
        """
        Test if subtraction of 1 from 2 results in 1.
        """
        assert 2 - 1 == 1

    def test_multiplication(self):
        """
        Test if multiplication of 2 and 3 results in 6.
        """
        assert 2 * 3 == 6

